#!/usr/bin/env python3
"""Render the tinyfs build into the published site.

    python3 experiments/tinyfs/render.py

Reads the newest run's report and `experiments/tinyfs/audit.json` and writes
`docs/tinyfs.html`, so the artefact a reader opens is generated from the same
evidence the gates produced - not written by hand afterwards.
"""

from __future__ import annotations

import html
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from minifleet.report import CSS  # noqa: E402


def newest_run() -> Path:
    runs = sorted(
        (path for path in (REPO / "runs" / "tinyfs").glob("*") if (path / "run.json").exists()),
        key=lambda path: (path / "run.json").stat().st_mtime,
    )
    if not runs:
        raise SystemExit("no tinyfs run found")
    return runs[-1]


def main() -> int:
    run_dir = newest_run()
    record = json.loads((run_dir / "run.json").read_text())
    audit = json.loads((REPO / "experiments" / "tinyfs" / "audit.json").read_text())
    rows = audit["rows"]
    passed = sum(1 for row in rows if row["ok"])

    def esc(value: object) -> str:
        return html.escape(str(value))

    gate_rows = "\n".join(
        f"<tr><td><code>{esc(row['gate'])}</code></td>"
        f"<td><span class='pill {'pass' if row['ok'] else 'fail'}'>"
        f"{'pass' if row['ok'] else 'fail'}</span></td>"
        f"<td class='muted'>{esc(row['detail'][:150])}</td></tr>"
        for row in rows
    )
    evidence_rows = "\n".join(
        f"<tr><td><code>{esc(item['gate_id'])}</code></td>"
        f"<td><span class='pill {'pass' if item['status'] == 'pass' else 'fail'}'>"
        f"{esc(item['status'])}</span></td>"
        f"<td><code>{esc(json.dumps(item['metrics']) if item['metrics'] else '')}</code></td>"
        f"<td class='muted'>{esc((item.get('detail') or '')[:160])}</td></tr>"
        for item in record["evidence"][-12:]
    )
    tasks = "\n".join(
        f"<tr><td><code>{esc(task['id'])}</code></td><td>{esc(task['state'])}</td>"
        f"<td><code>{esc(', '.join(task['owns']))}</code></td></tr>"
        for task in record["design"]["tasks"]
    )

    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>tinyfs - a crash-consistent filesystem, built and audited by the fleet</title>
<style>{CSS}</style></head>
<body>
<header>
  <h1>tinyfs: a crash-consistent filesystem core</h1>
  <div class="muted">Produced by MiniFleet from a prose intent, judged by gates the builders
  could not edit, then re-audited from a clean export.</div>
  <div class="cards">
    <div class="card"><div class="k">Run verdict</div><div class="v">{esc(record['status'])}</div></div>
    <div class="card"><div class="k">Gate observations</div><div class="v">{len(record['evidence'])}</div></div>
    <div class="card"><div class="k">Audit checks</div><div class="v">{passed}/{len(rows)}</div></div>
    <div class="card"><div class="k">Components</div><div class="v">{len(record['design']['tasks'])}</div></div>
  </div>
</header>
<main>
  <h2>1. The audit, from a <code>git archive</code> export</h2>
  <p class="muted">Every row below was produced by re-running the run's own gates and then
  pushing past them: {esc(audit['tree'])}</p>
  <table><thead><tr><th>Check</th><th>Result</th><th>Detail</th></tr></thead>
  <tbody>{gate_rows}</tbody></table>

  <h2>2. The task graph that produced it</h2>
  <table><thead><tr><th>Task</th><th>State</th><th>Write scope</th></tr></thead>
  <tbody>{tasks}</tbody></table>

  <h2>3. The run's last gate observations</h2>
  <table><thead><tr><th>Gate</th><th>Status</th><th>Metrics</th><th>Detail</th></tr></thead>
  <tbody>{evidence_rows}</tbody></table>

  <h2>4. What is being claimed, and what is not</h2>
  <ul>
    <li>The promise checked is narrow and specific: after <code>fsync</code> returns, the data
    survives a crash, and the structure is never left inconsistent - at any of 120 injected
    power-loss points plus 40 double faults.</li>
    <li>The checker (<code>tools/minifleet_checks.py</code>) and the acceptance harness travel
    with the product and are compared byte for byte against their source, so the criteria
    cannot have been edited to fit the result.</li>
    <li>Not claimed: concurrency (one process owns the image), directories, large files
    (four data blocks per file), or a real block device.</li>
  </ul>
</main>
<footer>Generated by experiments/tinyfs/render.py from the run record and the audit - no claim
here exists without the evidence next to it.</footer>
</body></html>
"""
    docs = REPO / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "tinyfs.html").write_text(page)
    shutil.copy2(run_dir / "report.html", docs / "tinyfs-run.html")
    print(f"wrote {docs / 'tinyfs.html'}")
    print(f"wrote {docs / 'tinyfs-run.html'} from {run_dir.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
